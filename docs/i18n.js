russianTranslations.Language = 'Язык';
(() => {
  const englishTranslations = Object.fromEntries(Object.entries(russianTranslations).map(([en, ru]) => [ru, en]));
  let language = new URL(location.href).searchParams.get('lang') === 'ru' ? 'ru' : 'en';
  function setLanguage(next, updateUrl = false) {
    language = next === 'ru' ? 'ru' : 'en';
    const dictionary = language === 'ru' ? russianTranslations : englishTranslations;
    const translate = value => {
      const key = value.trim();
      return dictionary[key] ? value.replace(key, dictionary[key]) : value;
    };
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
      const node = walker.currentNode;
      if (node.parentElement.closest('script, style')) continue;
      node.nodeValue = translate(node.nodeValue);
    }
    document.querySelectorAll('[aria-label]').forEach(element => {
      element.setAttribute('aria-label', translate(element.getAttribute('aria-label')));
    });
    const description = document.querySelector('meta[name="description"]');
    description.content = translate(description.content);
    document.title = translate(document.title);
    document.documentElement.lang = language;
    document.querySelectorAll('[data-language]').forEach(button => {
      button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    if (updateUrl) {
      const url = new URL(location.href);
      if (language === 'ru') url.searchParams.set('lang', 'ru');
      else url.searchParams.delete('lang');
      history.replaceState(null, '', url);
    }
    document.dispatchEvent(new Event('languagechange'));
  }
  window.siteI18n = {
    get language() { return language; },
    t(english) { return language === 'ru' ? russianTranslations[english] || english : english; }
  };
  document.querySelectorAll('[data-language]').forEach(button => {
    button.addEventListener('click', () => setLanguage(button.dataset.language, true));
  });
  setLanguage(language);
})();
